    /// メッセージの番号(時間帯 × 10 + 0〜9)。同じ日の同じ時間帯では、なるべく重複させない
    static func pick(at date: Date, usedToday: Set<Int>) -> Int {
        let slot = TimeSlot.of(date)
        let all = (0..<10).map { (slot - 1) * 10 + $0 }
        let unused = all.filter { !usedToday.contains($0) }
        return (unused.isEmpty ? all : unused).randomElement() ?? 0
    }

    static func text(_ id: Int) -> String {
        all[max(0, min(4, id / 10))][max(0, min(9, id % 10))]
